#!/bin/bash
# daily-build.sh — unattended daily image build for immutable-ubuntu.
#
# This is the "publisher" side of the daily update story. Once a day (via
# the bundled systemd timer) it builds a fresh image from whatever the
# Ubuntu archives currently contain, and publishes it as a new YYYYMMDD.N
# version — but only when the installed package set actually changed.
# Clients' systemd-sysupdate timers then pick the new version up on their
# own schedule; nothing on a client changes until it reboots.
#
# Safety properties (safe to run blind from a timer):
#   - a second instance exits quietly (flock)
#   - a failed build never moves the published set (publish happens last,
#     only on success)
#   - an unchanged package set produces no new version at all, so clients
#     on metered connections don't download a redundant full tarball
#   - pruning regenerates + re-signs SHA256SUMS so the index always matches
#     what's on disk
#
# Change detection: mkosi writes a JSON manifest of installed packages
# (ManifestFormat=json). The script compares the new manifest's package
# set against the last published one. mkosi builds are not bit-
# reproducible (timestamps etc.), so comparing artifact hashes would
# always "differ" — the manifest is the deterministic signal.
#
# Usage:
#   sudo ./daily-build.sh [--release noble] [--out /srv/immutable]
#                         [--sign <gpg-key-id>] [--keep 14]
#                         [--force] [--dry-run]
#
# Environment (used when the flag is absent; handy for the systemd unit):
#   DAILY_RELEASE, DAILY_OUT, DAILY_SIGN, DAILY_KEEP
#
# Unattended signing: gpg must sign without interaction. Use a dedicated
# passwordless signing subkey or a gpg-agent with a preset passphrase.
# Without --sign the manifest is published unsigned — clients with
# Verify= will reject it, so either sign or run by hand and sign after.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$SCRIPT_DIR")"
MKOSI_DIR="$REPO_ROOT/mkosi"

RELEASE="${DAILY_RELEASE:-noble}"
OUT="${DAILY_OUT:-./out}"
SIGN="${DAILY_SIGN:-}"
KEEP="${DAILY_KEEP:-14}"
FORCE=0
DRY_RUN=0

fail() { echo "daily-build: ERROR: $*" >&2; exit 1; }
info() { echo "daily-build: $*"; }
warn() { echo "daily-build: WARNING: $*" >&2; }

while [ $# -gt 0 ]; do
    case "$1" in
        --release) RELEASE="$2"; shift 2;;
        --out) OUT="$2"; shift 2;;
        --sign) SIGN="$2"; shift 2;;
        --keep) KEEP="$2"; shift 2;;
        --force) FORCE=1; shift;;
        --dry-run) DRY_RUN=1; shift;;
        -h|--help) sed -n '2,32p' "$0"; exit 0;;
        *) fail "unknown argument: $1";;
    esac
done

[ "$DRY_RUN" = "1" ] || [ "$(id -u)" = "0" ] || fail "mkosi needs root (sudo)"
[ "$DRY_RUN" = "1" ] || command -v mkosi >/dev/null 2>&1 || fail "mkosi not found"
command -v python3 >/dev/null 2>&1 || fail "python3 not found (needed for manifest comparison)"

# -- dry-run: report the plan without touching anything ---------------------
if [ "$DRY_RUN" = "1" ]; then
    stamp="$(date +%Y%m%d)"
    n=1
    if [ -d "$OUT/$RELEASE" ]; then
        while [ -e "$OUT/$RELEASE/ubuntu_${stamp}.${n}.efi" ]; do n=$((n + 1)); done
    fi
    info "would build version ${stamp}.${n} for Ubuntu $RELEASE from current archive packages"
    info "would publish to $OUT/$RELEASE/ only if the package manifest differs from the last published version"
    info "would keep the newest $KEEP versions and regenerate SHA256SUMS${SIGN:+ + SHA256SUMS.gpg}"
    exit 0
fi

# -- single instance ----------------------------------------------------------
LOCKFILE="/var/lock/immutable-daily-build.lock"
exec 9>"$LOCKFILE"
flock -n 9 || { info "another build is already running; exiting quietly"; exit 0; }

# -- disk space guard (a full image build needs room to breathe) ---------------
MIN_FREE_GB=15
free_gb="$(df --output=avail -BG "$OUT" 2>/dev/null | tail -1 | tr -dc '0-9' || echo 0)"
[ "$free_gb" -ge "$MIN_FREE_GB" ] || fail "only ${free_gb}G free under $OUT (need ${MIN_FREE_GB}G); refusing to build"

# -- version for today ----------------------------------------------------------
stamp="$(date +%Y%m%d)"
DESTDIR="$OUT/$RELEASE"
mkdir -p "$DESTDIR"
n=1
while [ -e "$DESTDIR/ubuntu_${stamp}.${n}.efi" ]; do n=$((n + 1)); done
VERSION="${stamp}.${n}"
info "building version $VERSION for Ubuntu $RELEASE"

# -- stamp the version into the build (as publish.sh does) plus manifest ------
# Note: current mkosi wants KernelCommandLine in [Content], not [Output].
mkdir -p "$MKOSI_DIR/mkosi.conf.d"
cat > "$MKOSI_DIR/mkosi.conf.d/99-version.conf" <<EOF
# Generated by daily-build.sh — do not edit by hand.
[Distribution]
Release=$RELEASE

[Output]
ImageVersion=$VERSION
ManifestFormat=json

[Content]
KernelCommandLine=immutable.version=$VERSION
EOF
cleanup_dropin() { rm -rf "$MKOSI_DIR/mkosi.conf.d"; }
trap cleanup_dropin EXIT

info "building system tree (mkosi --format=tar) ..."
(cd "$MKOSI_DIR" && mkosi --format=tar)
info "building UKI (mkosi --format=uki) ..."
# See publish.sh: UnifiedKernelImages must be explicitly 'unsigned' or
# current mkosi silently skips ukify assembly on auto. Scoped to this
# invocation so the tarball stays free of bootloader bits.
cat > "$MKOSI_DIR/mkosi.conf.d/98-uki.conf" <<EOF
# Generated by daily-build.sh — do not edit by hand.
[Content]
Bootloader=systemd-boot
UnifiedKernelImages=unsigned
UnifiedKernelImageFormat=immutable-ubuntu
EOF
(cd "$MKOSI_DIR" && mkosi --format=uki)
rm -f "$MKOSI_DIR/mkosi.conf.d/98-uki.conf"

tar_src="$(ls -t "$MKOSI_DIR"/mkosi.output/immutable-ubuntu.tar* 2>/dev/null | head -1 || true)"
efi_src="$(ls -t "$MKOSI_DIR"/mkosi.output/immutable-ubuntu*.efi 2>/dev/null | head -1 || true)"
if [ -z "$tar_src" ] || [ -z "$efi_src" ]; then
    echo "daily-build: contents of $MKOSI_DIR/mkosi.output/:" >&2
    ls -la "$MKOSI_DIR/mkosi.output/" >&2 || true
fi
[ -n "$tar_src" ] || fail "mkosi tar output not found under $MKOSI_DIR/mkosi.output/"
[ -n "$efi_src" ] || fail "mkosi UKI output not found under $MKOSI_DIR/mkosi.output/"

# -- change detection: compare package manifests ------------------------------
# The JSON schema isn't pinned by mkosi's docs, so parse defensively:
# collect every {name, version} pair anywhere in the document.
manifest_src="$(ls -t "$MKOSI_DIR"/mkosi.output/immutable-ubuntu*.manifest* 2>/dev/null | head -1 || true)"
new_manifest="$(mktemp)"
if [ -n "$manifest_src" ]; then
    python3 - "$manifest_src" > "$new_manifest" <<'PYEOF'
import json, sys
def walk(o, out):
    if isinstance(o, dict):
        if isinstance(o.get("name"), str) and isinstance(o.get("version"), str):
            out.add(f"{o['name']}={o['version']}")
        for v in o.values():
            walk(v, out)
    elif isinstance(o, list):
        for v in o:
            walk(v, out)
found = set()
walk(json.load(open(sys.argv[1])), found)
if not found:
    sys.exit(3)  # manifest present but no packages parsed: schema changed?
print("\n".join(sorted(found)))
PYEOF
    parse_rc=$?
else
    parse_rc=3
fi

last_manifest="$(ls -v "$DESTDIR"/ubuntu_*.manifest.json 2>/dev/null | tail -1 || true)"
changed=1
if [ "$parse_rc" -ne 0 ]; then
    warn "could not parse a package manifest from the mkosi output (rc=$parse_rc); treating as changed"
elif [ -z "$last_manifest" ]; then
    info "no previously published manifest; treating as changed (first publish)"
elif cmp -s "$new_manifest" "$last_manifest"; then
    changed=0
fi

if [ "$changed" = "0" ] && [ "$FORCE" = "0" ]; then
    info "package set unchanged since $(basename "$last_manifest" .manifest.json); no new version published"
    rm -f "$new_manifest"
    exit 0
fi
[ "$FORCE" = "1" ] && [ "$changed" = "0" ] && info "--force: publishing despite unchanged package set"
info "package set changed; publishing version $VERSION"

# -- publish (only reached on a successful build with changes) ----------------
tar_name="ubuntu_${VERSION}.root.tar.zst"
efi_name="ubuntu_${VERSION}.efi"
cp "$tar_src" "$DESTDIR/$tar_name"
cp "$efi_src" "$DESTDIR/$efi_name"
[ "$parse_rc" = "0" ] && cp "$new_manifest" "$DESTDIR/ubuntu_${VERSION}.manifest.json"
printf '%s' "$RELEASE" > "$DESTDIR/release"
rm -f "$new_manifest"

# -- prune old versions, then (re)build the index to match --------------------
mapfile -t efis < <(ls -v "$DESTDIR"/ubuntu_*.efi 2>/dev/null || true)
if [ "${#efis[@]}" -gt "$KEEP" ]; then
    drop=$(( ${#efis[@]} - KEEP ))
    info "pruning $drop old version(s), keeping newest $KEEP"
    for (( i=0; i<drop; i++ )); do
        base="$(basename "${efis[$i]}" .efi)"
        rm -f "$DESTDIR/$base.efi" "$DESTDIR/$base.root.tar.zst" "$DESTDIR/$base.manifest.json"
        info "  pruned $base"
    done
fi

(cd "$DESTDIR" && sha256sum ubuntu_*.efi ubuntu_*.root.tar.zst > SHA256SUMS)
if [ -n "$SIGN" ]; then
    (cd "$DESTDIR" && gpg --batch --detach-sign --armor --local-user "$SIGN" --output SHA256SUMS.gpg SHA256SUMS)
    info "signed SHA256SUMS with $SIGN"
else
    rm -f "$DESTDIR/SHA256SUMS.gpg"
    warn "SHA256SUMS published unsigned (set DAILY_SIGN or --sign; clients with Verify= will reject it)"
fi

cat <<EOF

daily-build: done -> $DESTDIR/
  $tar_name
  $efi_name
  ubuntu_${VERSION}.manifest.json
  SHA256SUMS${SIGN:+.gpg}

Serve \$DESTDIR over HTTPS; clients' systemd-sysupdate timers pick up
version $VERSION on their next check.
EOF
