#!/bin/bash
# publish.sh — build immutable-ubuntu artifacts with mkosi and publish them.
#
# Produces, in <out>/<release>/:
#   ubuntu_<version>.root.tar.zst   versioned system tree (mkosi --format=tar)
#   ubuntu_<version>.efi            unified kernel image  (mkosi --format=uki)
#   SHA256SUMS                      manifest consumed by systemd-sysupdate
#   SHA256SUMS.gpg                   (with --sign <key-id>)
#   release                         codename file read by transition.sh
#
# Version scheme: YYYYMMDD.N (e.g. 20261021.1), sortable and a valid
# sysupdate version string.
#
# Usage:
#   sudo ./publish.sh [--release noble] [--version 20261021.1]
#                     [--out ./out] [--sign <gpg-key-id>] [--skip-verify]
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$SCRIPT_DIR")"
MKOSI_DIR="$REPO_ROOT/mkosi"

RELEASE="noble"
VERSION=""
OUT="./out"
SIGN=""
SKIP_VERIFY=0

fail() { echo "publish: ERROR: $*" >&2; exit 1; }
info() { echo "publish: $*"; }

while [ $# -gt 0 ]; do
    case "$1" in
        --release) RELEASE="$2"; shift 2;;
        --version) VERSION="$2"; shift 2;;
        --out) OUT="$2"; shift 2;;
        --sign) SIGN="$2"; shift 2;;
        --skip-verify) SKIP_VERIFY=1; shift;;
        -h|--help) sed -n '2,16p' "$0"; exit 0;;
        *) fail "unknown argument: $1";;
    esac
done

[ "$(id -u)" = "0" ] || fail "mkosi needs root (sudo)"
command -v mkosi >/dev/null 2>&1 || fail "mkosi not found (apt install mkosi)"

if [ -z "$VERSION" ]; then
    stamp="$(date +%Y%m%d)"
    n=1
    while [ -e "$OUT/$RELEASE/ubuntu_${stamp}.${n}.efi" ]; do n=$((n + 1)); done
    VERSION="${stamp}.${n}"
fi
info "building version $VERSION for Ubuntu $RELEASE"

# Inject the version into the mkosi build: os-release IMAGE_VERSION and the
# UKI kernel command line (the initrd hook mounts the matching tree).
# Note: current mkosi wants KernelCommandLine in [Content], not [Output].
mkdir -p "$MKOSI_DIR/mkosi.conf.d"
cat > "$MKOSI_DIR/mkosi.conf.d/99-version.conf" <<EOF
# Generated by publish.sh — do not edit by hand.
[Distribution]
Release=$RELEASE

[Output]
ImageVersion=$VERSION

[Content]
KernelCommandLine=immutable.version=$VERSION
EOF

DESTDIR="$OUT/$RELEASE"
mkdir -p "$DESTDIR"

info "building system tree (mkosi --format=tar) ..."
(cd "$MKOSI_DIR" && mkosi --format=tar)
info "building UKI (mkosi --format=uki) ..."
(cd "$MKOSI_DIR" && mkosi --format=uki)

# mkosi names outputs after Output= (immutable-ubuntu) + format suffix.
# mkosi's exact output names vary by version (it may append _$version to
# the UKI name), so match by prefix and take the newest. On a miss, dump
# the directory so the log shows what mkosi actually produced.
tar_src="$(ls -t "$MKOSI_DIR"/mkosi.output/immutable-ubuntu.tar* 2>/dev/null | head -1 || true)"
efi_src="$(ls -t "$MKOSI_DIR"/mkosi.output/immutable-ubuntu*.efi 2>/dev/null | head -1 || true)"
if [ -z "$tar_src" ] || [ -z "$efi_src" ]; then
    echo "publish: contents of $MKOSI_DIR/mkosi.output/:" >&2
    ls -la "$MKOSI_DIR/mkosi.output/" >&2 || true
fi
[ -n "$tar_src" ] || fail "mkosi tar output not found under $MKOSI_DIR/mkosi.output/"
[ -n "$efi_src" ] || fail "mkosi UKI output not found under $MKOSI_DIR/mkosi.output/"

tar_name="ubuntu_${VERSION}.root.tar.zst"
efi_name="ubuntu_${VERSION}.efi"
cp "$tar_src" "$DESTDIR/$tar_name"
cp "$efi_src" "$DESTDIR/$efi_name"
printf '%s' "$RELEASE" > "$DESTDIR/release"

# Verify the initrd inside the UKI actually contains our /usr mount hook.
# (Catches the case where mkosi built the initrd without initramfs-tools.)
if [ "$SKIP_VERIFY" = "0" ]; then
    if command -v objcopy >/dev/null 2>&1 && command -v lsinitramfs >/dev/null 2>&1; then
        _initrd="$(mktemp)"
        if objcopy --dump-section .initrd="$_initrd" "$DESTDIR/$efi_name" 2>/dev/null \
            && lsinitramfs "$_initrd" 2>/dev/null | grep -q 'local-premount/immutable-usr'; then
            info "verified: immutable-usr hook present in UKI initrd"
        else
            fail "immutable-usr hook NOT found in UKI initrd — the versioned /usr would never mount. See docs/DESIGN.md (initrd assumptions)."
        fi
        rm -f "$_initrd"
    else
        info "objcopy/lsinitramfs missing; skipping initrd hook verification (see docs/DESIGN.md)"
    fi
fi

# Manifest for systemd-sysupdate (SHA256SUMS.gpg optional but recommended).
(cd "$DESTDIR" && sha256sum "$tar_name" "$efi_name" > SHA256SUMS)
if [ -n "$SIGN" ]; then
    (cd "$DESTDIR" && gpg --detach-sign --armor --local-user "$SIGN" --output SHA256SUMS.gpg SHA256SUMS)
    info "signed SHA256SUMS with $SIGN"
else
    info "SHA256SUMS written unsigned (use --sign <key-id>; clients verify with Verify= + import-pubring)"
fi

# Clean the generated version drop-in so the tree stays pristine.
rm -rf "$MKOSI_DIR/mkosi.conf.d"

cat <<EOF

publish: done -> $DESTDIR/
  $tar_name
  $efi_name
  SHA256SUMS${SIGN:+.gpg}

Serve \$DESTDIR over HTTPS and point clients' transfer [Source] Path at it,
or hand the directory to transition.sh --artifacts for a local install.
EOF
